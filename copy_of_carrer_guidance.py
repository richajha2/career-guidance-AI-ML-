def normalize_technology(x):

    x = str(x).strip().casefold()
    x = re.sub(r"\s+", " ", x)
    x = x.rstrip(".")


    # AI / ML
    if x in [
        "ai",
        "ai / ml",
        "ai/ml",
        "ai-ml",
        "ai / machine learning"
    ]:
        return "AI/ML"


    # Cybersecurity
    if x in [
        "cybersecurity",
        "cyber security"
    ]:
        return "Cybersecurity"


    # Cloud
    if x in [
        "cloud",
        "cloud computing",
        "cloud technologies",
        "cloud infrastructure",
        "cloud/infrastructure",
        "cloud & infrastructure"
    ]:
        return "Cloud"


    # Data Analytics
    if x in [
        "data analytics",
        "data analytics/bi",
        "data analytics / bi",
        "data analytics & bi",
        "data analytics / data engineering",
        "data analytics / data science",
        "data & analytics",
        "analytics and reporting"
    ]:
        return "Data Analytics"


    # Data Science
    if x in [
        "data science",
        "datascience",
        "data science & analytics",
        "data science / data analytics"
    ]:
        return "Data Science"


    # Data Engineering
    if x in [
        "data engineering",
        "data engineering & analytics"
    ]:
        return "Data Engineering"


    # Software Development
    if (
        "software development" in x
        or "software developer" in x
        or "software engineer" in x
        or "software engineering" in x
        or x == "software development/sde"
        or x == "software developer/ ai/ml"
    ):
        return "Software Development"


    # Web Development
    if (
        "web development" in x
        or "web/app development" in x
        or "web & app development" in x
        or "web/mobile development" in x
    ):
        return "Web Development"


    # Full Stack
    if "full stack" in x:
        return "Full Stack"


    # FinTech
    if (
        "fintech" in x
        or "financial technology" in x
    ):
        return "FinTech"


    # DevOps
    if "devops" in x:
        return "DevOps"


    # Automation
    if (
        "automation" in x
        or x == "rpa"
        or "rpa/automation" in x
    ):
        return "Automation"


    # Database
    if (
        "database" in x
        or x == "databases"
        or "database/sql" in x
    ):
        return "Database"


    # API
    if x.startswith("api"):
        return "API"


    # UI/UX
    if "ui/ux" in x:
        return "UI/UX"


    # QA / Testing
    if (
        "qa" in x
        or "testing" in x
    ):
        return "QA/Testing"


    # Mobile
    if "mobile" in x:
        return "Mobile Development"


    # Payment
    if (
        "payment" in x
        or "payments" in x
    ):
        return "Payment Technology"


    # Blockchain
    if "blockchain" in x:
        return "Blockchain"


    # IoT
    if x == "iot" or x.startswith("iot/"):
        return "IoT"


    # NLP
    if x == "nlp":
        return "NLP"


    # Generative AI
    if (
        "genai" in x
        or "generative ai" in x
    ):
        return "Generative AI"


    # Robotics
    if "robotics" in x:
        return "Robotics"


    # Semiconductor
    if "semiconductor" in x:
        return "Semiconductor"


    # E-commerce
    if (
        "e-commerce" in x
        or "ecommerce" in x
    ):
        return "E-commerce"


    # Keep remaining technology
    return x.title()


